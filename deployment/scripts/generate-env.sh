#!/usr/bin/env bash
# =============================================================================
# generate-env.sh
# Runs ON the GCP VM (called remotely via SSH by Bitbucket Pipelines).
# Writes all .env files to /opt/querylab from environment variables passed in
# the SSH command. Never committed to git — secrets stay in Bitbucket Secure
# Variables and are injected at deploy time.
# =============================================================================
set -euo pipefail

DEPLOY_DIR="${DEPLOY_DIR:-/opt/querylab}"
echo "[generate-env] Writing .env files to $DEPLOY_DIR"

# ── .env.agent ───────────────────────────────────────────────────────────────
cat > "$DEPLOY_DIR/.env.agent" <<EOF
# Auto-generated by generate-env.sh — do not edit manually
OPENAI_API_KEY=${OPENAI_API_KEY}
OPENAI_MODEL=${OPENAI_MODEL:-gpt-4o-mini}
QUERYLAB_AGENTS_LOG_LEVEL=${QUERYLAB_AGENTS_LOG_LEVEL:-INFO}
QUERYLAB_AGENTS_LOG_FORMAT=${QUERYLAB_AGENTS_LOG_FORMAT:-json}

# Langsmith (optional)
LANGSMITH_TRACING=${LANGSMITH_TRACING:-true}
LANGSMITH_ENDPOINT=${LANGSMITH_ENDPOINT:-https://api.smith.langchain.com}
LANGSMITH_API_KEY=${LANGSMITH_API_KEY:-}
LANGSMITH_PROJECT=${LANGSMITH_PROJECT:-querylab-prod}
EOF

# ── .env.orchestrator ────────────────────────────────────────────────────────
cat > "$DEPLOY_DIR/.env.orchestrator" <<EOF
# Auto-generated by generate-env.sh — do not edit manually
OPENAI_API_KEY=${OPENAI_API_KEY}
OPENAI_MODEL=${OPENAI_MODEL:-gpt-4o-mini}
SECRET_KEY=${SECRET_KEY}
ALGORITHM=HS256
ACCESS_TOKEN_EXPIRE_MINUTES=1440
BACKEND_DB_HOST=${BACKEND_DB_HOST}
BACKEND_DB_PORT=${BACKEND_DB_PORT:-3306}
BACKEND_DB_USER=${BACKEND_DB_USER}
BACKEND_DB_PASSWORD=${BACKEND_DB_PASSWORD}
BACKEND_DB_DATABASE=${BACKEND_DB_DATABASE}
QUERYLAB_AGENTS_API_URL=http://${GCP_VM_IP}:8000
ORCHESTRATOR_LOG_FORMAT=${ORCHESTRATOR_LOG_FORMAT:-json}
EOF

# ── .env.revenue.mcp ─────────────────────────────────────────────────────────
cat > "$DEPLOY_DIR/.env.revenue.mcp" <<EOF
# Auto-generated by generate-env.sh — do not edit manually
MYSQL_HOST=${REVENUE_MYSQL_HOST}
MYSQL_PORT=${REVENUE_MYSQL_PORT:-3306}
MYSQL_USER=${REVENUE_MYSQL_USER}
MYSQL_PASSWORD=${REVENUE_MYSQL_PASSWORD}
MYSQL_DATABASE=${REVENUE_MYSQL_DATABASE}
MCP_HOST=0.0.0.0
MCP_PORT=8000
MCP_TRANSPORT=streamable-http
MCP_LOG_LEVEL=INFO
EOF

# ── .env.beat.mcp ────────────────────────────────────────────────────────────
cat > "$DEPLOY_DIR/.env.beat.mcp" <<EOF
# Auto-generated by generate-env.sh — do not edit manually
MYSQL_HOST=${BEAT_MYSQL_HOST}
MYSQL_PORT=${BEAT_MYSQL_PORT:-3306}
MYSQL_USER=${BEAT_MYSQL_USER}
MYSQL_PASSWORD=${BEAT_MYSQL_PASSWORD}
MYSQL_DATABASE=${BEAT_MYSQL_DATABASE}
MCP_HOST=0.0.0.0
MCP_PORT=8000
MCP_TRANSPORT=streamable-http
MCP_LOG_LEVEL=INFO
EOF

# ── .env.meridian.mcp ────────────────────────────────────────────────────────
cat > "$DEPLOY_DIR/.env.meridian.mcp" <<EOF
# Auto-generated by generate-env.sh — do not edit manually
MYSQL_HOST=${MERIDIAN_MYSQL_HOST}
MYSQL_PORT=${MERIDIAN_MYSQL_PORT:-3306}
MYSQL_USER=${MERIDIAN_MYSQL_USER}
MYSQL_PASSWORD=${MERIDIAN_MYSQL_PASSWORD}
MYSQL_DATABASE=${MERIDIAN_MYSQL_DATABASE}
MCP_HOST=0.0.0.0
MCP_PORT=8000
MCP_TRANSPORT=streamable-http
MCP_LOG_LEVEL=INFO
EOF

# ── .env.weaviate.mcp ────────────────────────────────────────────────────────
cat > "$DEPLOY_DIR/.env.weaviate.mcp" <<EOF
# Auto-generated by generate-env.sh — do not edit manually
WEAVIATE_HOST=${WEAVIATE_HOST}
WEAVIATE_PORT=${WEAVIATE_PORT}
WEAVIATE_API_KEY=${WEAVIATE_API_KEY}
OPENAI_API_KEY=${OPENAI_API_KEY}
WEAVIATE_EMBEDDING_MODEL=${WEAVIATE_EMBEDDING_MODEL:-text-embedding-3-small}
MCP_HOST=0.0.0.0
MCP_PORT=8001
MCP_TRANSPORT=streamable-http
MCP_LOG_LEVEL=INFO
DOCKER_RUNNING=true
EOF

echo "[generate-env] All .env files written successfully."
